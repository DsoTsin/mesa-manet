#ifndef AGC_RUNTIME_H
#define AGC_RUNTIME_H

#include "agc_types.h"

#define AGC_RUNTIME_BASE UINT64_C(0x20000000000)
#define AGC_RUNTIME_BYTES (UINT64_C(64) << 20)

#define AGC_RUNTIME_DESCRIPTOR_LUT_VA (AGC_RUNTIME_BASE + UINT64_C(0x0))
#define AGC_RUNTIME_DESCRIPTOR_LUT_BYTES UINT64_C(18944)
#define AGC_RUNTIME_MIP_STATS_VA (AGC_RUNTIME_BASE + UINT64_C(0x10000))
#define AGC_RUNTIME_MIP_STATS_BYTES UINT64_C(2048)
#define AGC_RUNTIME_MIP_STATS_TEMPLATE_VA (AGC_RUNTIME_MIP_STATS_VA + AGC_RUNTIME_MIP_STATS_BYTES)
#define AGC_MIP_STATS_REPORT_SLOTS_OFFSET 64u
#define AGC_MIP_STATS_REPORT_BYTES (AGC_MIP_STATS_REPORT_SLOTS_OFFSET + (uint32_t)AGC_RUNTIME_MIP_STATS_BYTES)
#define AGC_RUNTIME_GDS_VA (AGC_RUNTIME_BASE + UINT64_C(0x20000))
#define AGC_RUNTIME_GDS_BYTES UINT64_C(0x10000)
#define AGC_RUNTIME_GDS_BUFFER_BYTES UINT64_C(0x10010)
#define AGC_RUNTIME_IMAGE_REPORTS_VA (AGC_RUNTIME_BASE + UINT64_C(0x40000))
#define AGC_RUNTIME_IMAGE_REPORTS_BYTES UINT64_C(0x50000)
#define AGC_RUNTIME_ATTRIBUTE_RING_VA (AGC_RUNTIME_BASE + UINT64_C(0x100000))
#define AGC_RUNTIME_ATTRIBUTE_RING_MAX_BYTES (UINT64_C(16) << 20)
#define AGC_RUNTIME_TABLES_END (AGC_RUNTIME_ATTRIBUTE_RING_VA + AGC_RUNTIME_ATTRIBUTE_RING_MAX_BYTES)

#define AGC_IMAGE_KNOWN_BUCKETS (UINT32_C(1) << 13)
#define AGC_IMAGE_KNOWN_BUCKET_BYTES 8u
#define AGC_IMAGE_KNOWN_BYTES (AGC_IMAGE_KNOWN_BUCKETS * AGC_IMAGE_KNOWN_BUCKET_BYTES)
#define AGC_IMAGE_REPORT_SLOTS (UINT32_C(1) << 12)
#define AGC_IMAGE_REPORT_BYTES 64u
#define AGC_IMAGE_REPORT_CHECK_OFFSET 32u
#define AGC_IMAGE_REPORTS_OFFSET AGC_IMAGE_KNOWN_BYTES
#define AGC_IMAGE_REPORT_TABLE_BYTES (AGC_IMAGE_REPORTS_OFFSET + AGC_IMAGE_REPORT_SLOTS * AGC_IMAGE_REPORT_BYTES)
#define AGC_IMAGE_REPORT_CHECK UINT32_C(0x5a3ca5c3)
#define AGC_IMAGE_REPORT_SPREAD UINT32_C(0x9e3779b9)
#define AGC_IMAGE_REPORT_STORE_CHECK UINT32_C(0xc35aa53c)
#define AGC_IMAGE_REPORT_STORE_SALT UINT32_C(0x7f4a7c15)

bool agc_runtime_init(char *error, size_t error_bytes);
void agc_runtime_mip_stats_empty(uint32_t words[AGC_RUNTIME_MIP_STATS_BYTES / 4]);

uint32_t agc_image_report_fold(const uint32_t tsharp[8]);
uint32_t agc_image_report_hash(const uint32_t tsharp[8], bool stored);
uint32_t agc_image_report_known_offset(uint32_t hash);
uint32_t agc_runtime_image_reports_take(uint32_t (*tsharps)[8], bool *stored, uint32_t capacity);
void agc_runtime_image_mark(const uint32_t tsharp[8], bool stored);
void agc_runtime_image_unmark(const uint32_t tsharp[8], bool stored);

#endif
