const uint32_t *
agc_surface_guest_equation(uint32_t swizzle_mode, bool thick, uint32_t element_log2)
{
   const uint32_t(*equations)[16];
   if (element_log2 >= 5)
      return NULL;
   if (thick) {
      switch (swizzle_mode) {
      case AGC_SW_4KB_S:
         equations = agc_surface_guest_4kb_s_thick;
         break;
      case AGC_SW_64KB_S:
         equations = agc_surface_guest_64kb_s_thick;
         break;
      case AGC_SW_4KB_S_X:
         equations = agc_surface_guest_4kb_s_x_thick;
         break;
      case AGC_SW_64KB_S_X:
         equations = agc_surface_guest_64kb_s_x_thick;
         break;
      case AGC_SW_64KB_D_X:
         equations = agc_surface_guest_64kb_d_x_thick;
         break;
      default:
         return NULL;
      }
   } else {
      switch (swizzle_mode) {
      case AGC_SW_256B_D:
         equations = agc_surface_guest_256b_d;
         break;
      case AGC_SW_4KB_D:
         equations = agc_surface_guest_4kb_d;
         break;
      case AGC_SW_64KB_D:
         equations = agc_surface_guest_64kb_d;
         break;
      case AGC_SW_64KB_S_T:
         equations = agc_surface_guest_64kb_s_t;
         break;
      case AGC_SW_64KB_D_T:
         equations = agc_surface_guest_64kb_d_t;
         break;
      case AGC_SW_4KB_S_X:
         equations = agc_surface_guest_4kb_s_x;
         break;
      case AGC_SW_4KB_D_X:
         equations = agc_surface_guest_4kb_d_x;
         break;
      case AGC_SW_64KB_Z_X:
         equations = agc_surface_guest_64kb_z_x;
         break;
      case AGC_SW_64KB_S_X:
         equations = agc_surface_guest_64kb_s_x;
         break;
      case AGC_SW_64KB_D_X:
         equations = agc_surface_guest_64kb_d_x;
         break;
      case AGC_SW_64KB_R_X:
         equations = agc_surface_guest_64kb_r_x;
         break;
      default:
         return NULL;
      }
   }
   return equations[element_log2];
}

const uint32_t *
agc_surface_host_equation(uint32_t swizzle_mode, uint32_t element_log2)
{
   const uint32_t(*equations)[16];
   if (element_log2 >= 5)
      return NULL;
   switch (swizzle_mode) {
   case AGC_SW_256B_D:
      equations = agc_surface_host_256b_d;
      break;
   case AGC_SW_4KB_D:
      equations = agc_surface_host_4kb_d;
      break;
   case AGC_SW_64KB_D:
      equations = agc_surface_host_64kb_d;
      break;
   case AGC_SW_64KB_D_T:
      equations = agc_surface_host_64kb_d_t;
      break;
   case AGC_SW_4KB_D_X:
      equations = agc_surface_host_4kb_d_x;
      break;
   case AGC_SW_64KB_Z_X:
      equations = agc_surface_host_64kb_z_x;
      break;
   case AGC_SW_64KB_D_X:
      equations = agc_surface_host_64kb_d_x;
      break;
   case AGC_SW_64KB_R_X:
      equations = agc_surface_host_64kb_r_x;
      break;
   default:
      return NULL;
   }
   for (uint32_t bit = 0; bit < AGC_SURFACE_EQUATION_BITS; bit++) {
      if (equations[element_log2][bit])
         return equations[element_log2];
   }
   return NULL;
}
